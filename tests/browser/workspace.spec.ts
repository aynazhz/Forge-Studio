import { expect, test } from '@playwright/test'
import { starterFiles } from '../../src/features/project/template'
import { writeEditor } from './editor'

test('creates and reopens projects, maintains files and tabs, and saves edits', async ({ page }) => {
  await page.goto('/')
  const explorer = page.getByRole('complementary', { name: 'Explorer' })
  const tabs = page.getByRole('navigation', { name: 'Open files' })
  const preview = page.frameLocator('iframe[title="React preview"]')
  const previewPanel = page.getByRole('region', { name: 'Preview' })
  const dialog = page.getByRole('dialog')
  const select = page.getByRole('combobox', { name: 'Open project' })

  await expect(preview.getByRole('heading', { name: 'Make it yours.' })).toBeVisible()
  await expect(previewPanel.getByRole('status')).toHaveText('Running')
  await page.screenshot({ path: test.info().outputPath('forge-studio.png') })
  await page.getByRole('button', { name: 'New project' }).click()
  await dialog.getByLabel('Name').fill('Browser project')
  await dialog.getByRole('button', { name: 'Create', exact: true }).click()
  await expect(select.locator('option:checked')).toHaveText('Browser project')

  await explorer.getByRole('button', { name: 'New folder' }).click()
  await dialog.getByLabel('Name').fill('modules')
  await dialog.getByLabel('Destination').selectOption({ label: 'Project root' })
  await dialog.getByRole('button', { name: 'Create', exact: true }).click()

  await explorer.getByRole('button', { name: 'New file' }).click()
  await dialog.getByLabel('Name').fill('snippet.ts')
  await expect(dialog.getByLabel('Destination').locator('option:checked')).toHaveText('/modules')
  await dialog.getByRole('button', { name: 'Create', exact: true }).click()
  await writeEditor(page, "export const snippet = 'Content from a new file'")
  await explorer.getByRole('button', { name: 'App.tsx', exact: true }).click()
  const app = starterFiles['/src/App.tsx']
    .replace("{ caption } from './caption'", "{ snippet as caption } from '../modules/snippet'")
    .replace('Make it yours.', 'Project editor')
  await writeEditor(page, app)
  await expect(preview.getByRole('heading', { name: 'Project editor' })).toBeVisible()
  await expect(preview.getByText('Content from a new file')).toBeVisible()
  await preview.getByRole('button', { name: 'Increment' }).click()
  await expect(preview.getByRole('status', { name: 'Count' })).toHaveText('1')

  await tabs.getByRole('button', { name: 'Close /modules/snippet.ts' }).click()
  await expect(tabs.getByRole('button', { name: 'App.tsx', exact: true })).toHaveAttribute('aria-current', 'true')
  await page.keyboard.press('ControlOrMeta+Shift+f')
  const search = explorer.getByRole('searchbox', { name: 'Search project' })
  await expect(search).toBeFocused()
  await search.fill('Content from a new file')
  await explorer.getByRole('button', { name: /snippet\.ts.*Content from a new file/ }).click()
  await expect(tabs.getByRole('button', { name: 'snippet.ts', exact: true })).toHaveAttribute('aria-current', 'true')
  await expect(page.locator('.view-line').first()).toContainText('Content from a new file')
  await page.getByRole('textbox', { name: 'Code editor', exact: true }).focus()
  await page.keyboard.press('ControlOrMeta+z')
  await expect(page.locator('.view-line').first()).not.toContainText('Content from a new file')
  await page.keyboard.press('ControlOrMeta+Shift+z')
  await expect(page.locator('.view-line').first()).toContainText('Content from a new file')

  await explorer.getByRole('button', { name: 'Rename selected item' }).click()
  await dialog.getByLabel('Name').fill('renamed.ts')
  await dialog.getByRole('button', { name: 'Rename', exact: true }).click()
  await expect(tabs.getByRole('button', { name: 'renamed.ts', exact: true })).toHaveAttribute('aria-current', 'true')
  await expect(previewPanel.getByRole('alert')).toContainText(/snippet/i)

  await explorer.getByRole('button', { name: 'Move selected item' }).click()
  await dialog.getByLabel('Destination').selectOption({ label: '/src' })
  await dialog.getByRole('button', { name: 'Move', exact: true }).click()
  await expect(tabs.getByRole('button', { name: 'Close /src/renamed.ts' })).toBeVisible()
  await expect(page.locator('.view-line').first()).toContainText('Content from a new file')
  await tabs.getByRole('button', { name: 'App.tsx', exact: true }).click()
  await writeEditor(page, app.replace('../modules/snippet', './renamed'))
  await expect(previewPanel.getByRole('alert')).toHaveCount(0)
  await expect(preview.getByText('Content from a new file')).toBeVisible()

  const divider = page.getByRole('separator', { name: 'Resize preview' })
  const before = (await previewPanel.boundingBox())!.width
  await divider.focus()
  await divider.press('ArrowLeft')
  const handle = (await divider.boundingBox())!
  await page.mouse.move(handle.x + 3, handle.y + handle.height / 2)
  await page.mouse.down()
  await page.mouse.move(handle.x - 65, handle.y + handle.height / 2, { steps: 4 })
  await page.mouse.up()
  await expect(divider).toHaveAttribute('aria-valuenow', /^(4[5-9]|5\d)$/)
  expect((await previewPanel.boundingBox())!.width).toBeGreaterThan(before + 40)

  await expect(page.getByText('Saved locally', { exact: true })).toBeVisible()
  await page.reload()
  await expect(select.locator('option:checked')).toHaveText('Browser project')
  await expect(tabs.getByRole('button', { name: 'App.tsx', exact: true })).toHaveAttribute('aria-current', 'true')
  await expect(preview.getByText('Content from a new file')).toBeVisible()
  await select.selectOption({ label: 'React Workbench' })
  await expect(preview.getByRole('heading', { name: 'Make it yours.' })).toBeVisible()
  await select.selectOption({ label: 'Browser project' })
  await expect(preview.getByRole('heading', { name: 'Project editor' })).toBeVisible()

  await explorer.getByRole('button', { name: 'renamed.ts', exact: true }).click()
  await explorer.getByRole('button', { name: 'Delete selected item' }).click()
  await dialog.getByRole('button', { name: 'Cancel' }).click()
  await expect(tabs.getByRole('button', { name: 'Close /src/renamed.ts' })).toBeVisible()
  await explorer.getByRole('button', { name: 'Delete selected item' }).click()
  await dialog.getByRole('button', { name: 'Delete', exact: true }).click()
  await expect(tabs.getByRole('button', { name: 'Close /src/renamed.ts' })).toHaveCount(0)
  await expect(previewPanel.getByRole('alert')).toContainText(/renamed/i)
})

test('validates names and asks before deleting a populated folder', async ({ page }) => {
  await page.goto('/')
  const explorer = page.getByRole('complementary', { name: 'Explorer' })
  const dialog = page.getByRole('dialog')
  const source = explorer.getByRole('button', { name: 'src', exact: true })
  await source.click()
  await expect(source).toHaveAttribute('aria-expanded', 'false')
  await explorer.getByRole('button', { name: 'New file' }).click()
  await dialog.getByLabel('Name').fill('app.tsx')
  await dialog.getByRole('button', { name: 'Create', exact: true }).click()
  await expect(dialog.getByRole('alert')).toContainText('already used')
  await dialog.getByLabel('Name').fill('bad/name')
  await dialog.getByRole('button', { name: 'Create', exact: true }).click()
  await expect(dialog.getByRole('alert')).toContainText('valid name')
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)
  await source.press('F2')
  await expect(dialog.getByLabel('Name')).toHaveValue('src')
  await page.keyboard.press('Escape')
  await explorer.getByRole('button', { name: 'Delete selected item' }).click()
  await expect(dialog).toContainText('3 nested items')
  await expect(dialog.getByRole('button', { name: 'Cancel' })).toBeFocused()
  await dialog.getByRole('button', { name: 'Delete', exact: true }).click()
  await expect(source).toHaveCount(0)
  await expect(page.getByText('No file open')).toBeVisible()
})

test('protects a newer IndexedDB save from a stale browser tab', async ({ context, page }) => {
  await page.goto('/')
  await expect(page.getByText('Saved locally', { exact: true })).toBeVisible()
  const stale = await context.newPage()
  await stale.goto('/')
  await expect(stale.getByText('Saved locally', { exact: true })).toBeVisible()

  await writeEditor(page, 'export default function App() { return <h1>Latest saved edit</h1> }')
  await expect(page.getByText('Saved locally', { exact: true })).toBeVisible()
  await writeEditor(stale, 'export default function App() { return <h1>Stale edit</h1> }')
  await expect(stale.getByText('Save failed', { exact: true })).toBeVisible()
  await expect(stale.getByText(/Another tab saved a newer workspace/)).toBeVisible()
  await stale.reload()
  await expect(stale.getByText('Saved locally', { exact: true })).toBeVisible()
  await expect(stale.locator('.view-line').first()).toContainText('Latest saved edit')
})

test('offers Monaco completion on a narrow viewport and reports an IndexedDB open error', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.addInitScript(() => {
    Object.defineProperty(window, 'indexedDB', {
      get() { throw new DOMException('Storage disabled for this browser test', 'SecurityError') },
    })
  })
  await page.goto('/')
  await expect(page.getByText('Session only', { exact: true })).toBeVisible()
  await expect(page.getByText(/Local storage is unavailable/)).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(390)
  await expect(page.getByRole('separator', { name: 'Resize preview' })).toBeHidden()
  await writeEditor(page, 'Math.ma')
  await page.keyboard.press('Control+Space')
  await expect(page.getByRole('option', { name: /^max/ })).toBeVisible()
})
